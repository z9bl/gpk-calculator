// Годичный потолок восстановления пропущенного срока на кассационное или
// надзорное обжалование — механика, а не предметная данная: одна и та же
// проверка «уложилось ли обстоятельство в год от даты вступления в силу»
// годится для любого процессуального кодекса, где закон вводит такой потолок
// (в ГПК — ч. 7 ст. 112 ГПК РФ в редакции Федерального закона от 01.04.2025
// № 49-ФЗ; до этой даты по существу та же норма была в абз. 2 ч. 6 ст. 112, с
// тем же конституционно-правовым толкованием — Постановление КС РФ от
// 01.06.2021 № 25-П). Этот модуль не знает ни о ГПК, ни о тексте нормы —
// только о двух датах и правиле «не позднее одного года».
//
// Область действия правила (текст нормы) — потолок касается ТОЛЬКО
// кассационных и надзорных жалоб/представлений, к апелляционному
// восстановлению (ч. 1–5 ст. 112) не относится. Это ограничение соблюдает не
// сам расчёт (ему всё равно, какие две даты ему передали), а вызывающий код —
// подключая проверку только к узлам кассации/надзора. См. CLAUDE.md о
// границах модулей: конкретный список таких узлов — предметные данные ГПК,
// им место в src/, а не здесь.
//
// «Не позднее одного года» — границы включительно: обстоятельство ровно в
// день годовщины вступления постановления в законную силу в потолок
// укладывается, на следующий день — уже нет. Год прибавляется как
// «соответствующее число через 12 месяцев» (тот же приём, что и в
// computeDeadline для duration.unit === 'year' — год есть 12 месяцев), а не
// как «365/366 календарных дней»: это чтение самого текста нормы («один
// год»), а не срок для совершения процессуального действия, поэтому здесь
// нет ни offset_start (день начинается точкой отсчёта, а не следующим за ней
// днём — норма считает от «дня вступления… в законную силу», а не «дня,
// следующего за» ним), ни shiftIfNonWorking (это не дедлайн действия, а
// фактическая граница периода, чей последний день закон не переносит на
// рабочий).

import { addMonths } from './engine.js';
import { toISO } from './term.js';
import { toISODate } from '../calendar/calendar.js';

const CAP_MONTHS = 12;

/**
 * Проверяет, укладывается ли дата обстоятельства, на которое заявитель
 * ссылается как на уважительную причину пропуска кассационного/надзорного
 * срока, в годичный потолок от даты вступления обжалуемого постановления в
 * законную силу.
 *
 * @param {Date|string|null} entryIntoForceDate — дата вступления обжалуемого
 *   судебного постановления в законную силу.
 * @param {Date|string|null} circumstanceDate — дата обстоятельства,
 *   приведённого как уважительная причина пропуска срока.
 * @returns {{within_cap:boolean, cap_deadline:string}|null} null, если
 *   какая-то из дат не задана или не распознана; иначе — within_cap (уложилось
 *   ли обстоятельство в потолок, включительно) и cap_deadline (последний день
 *   потолка, ISO).
 */
export function checkRestorationOneYearCap(entryIntoForceDate, circumstanceDate) {
  const entry = toISO(entryIntoForceDate);
  const circumstance = toISO(circumstanceDate);
  if (entry == null || circumstance == null) return null;

  const capDeadline = toISODate(addMonths(entry, CAP_MONTHS));
  return {
    within_cap: circumstance <= capDeadline,
    cap_deadline: capDeadline,
  };
}
